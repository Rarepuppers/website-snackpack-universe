function start(modeId) {
  if (DAILY && dailyAlreadyPlayed()) {
    announce("Today's challenge is already played. Come back tomorrow.");
    return;
  }
  state.mode = modeId;
  const seed = seedForRun();
  state.seed = seed;
  state.world = createWorld(modeId, seed);
  state.rules = createRules(seed, modeId);
  // createRules starts the game on ball 1 without going through nextBall, so
  // the first ball would otherwise be the only one with no save.
  armBallSave(state.rules);
  state.tape = RECORD ? [] : null;
  state.ballsLeft = MODES[modeId].balls;
  state.pendingKicks = [];
  state.running = true;
  state.paused = false;
  state.flashes.clear();
  el('pb-overlay').hidden = true;
  el('pb-modes').hidden = true;
  el('pb-hud').hidden = false;
  state.renderer.resize();
  setMusic('calm');
  paint();
  announce(`${MODES[modeId].label}. Hold the plunger.`);
}

/** Daily runs share a seed, so everyone gets the same missions in the same order. */
function seedForRun() {
  if (DAILY) {
    let h = 2166136261;
    for (let i = 0; i < DAILY.length; i += 1) {
      h ^= DAILY.charCodeAt(i);
      h = Math.imul(h, 16777619);
    }
    return h >>> 0;
  }
  return (Date.now() ^ Math.floor(Math.random() * 0xffffffff)) >>> 0;
}

