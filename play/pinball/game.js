/** ?daily=YYYY-MM-DD -- everyone gets the same missions, one attempt. */
const DAILY = new URLSearchParams(location.search).get('daily');

/**
 * ?record=1 -- capture a replay tape of this game.
 *
 * Records (dt, buttons) per FRAME, not per simulation step, because that is
 * what makes a real game reproducible: `advance()` is deterministic given the
 * same dt sequence and the same inputs, so replaying the recorded frames
 * reproduces the run exactly -- including the frame jitter of however the
 * machine happened to be running at the time. A tape recorded by a person
 * covers shot patterns and hesitation no scripted flipper loop will find.
 *
 * Play a game with ?record=1, then in the console:
 *     copy(JSON.stringify(window.__pbTape()))
 * and save it as tools/pinball/tapes/<name>.json.
 *
 * Costs nothing when the flag is absent: the array is never allocated.
 */
const RECORD = new URLSearchParams(location.search).has('record');
const TAPE_FRAME_CAP = 60 * 60 * 6; // ~6 minutes; a tape is not a memory leak

/**
 * Audio. Names resolve under shared-assets/game-ui/audio/pinball/ and are
 * generated by Codex per docs/pinball/05-codex-art-brief.md. Until they land
 * every call is a silent miss, which audio.js swallows by design -- a missing
 * effect must never surface as an error or change game logic.
 */
const SFX = window.SnackPackAudio ? window.SnackPackAudio.bank('pinball') : null;
const CUE_GAIN = {
  'spinner-tick': 0.55, 'post-1': 0.60, 'post-2': 0.60,
  'game-over': 0.80, 'tilt-warn': 0.80, tilt: 0.90,
};
function gainFor(name) {
  if (CUE_GAIN[name] != null) return CUE_GAIN[name];
  if (name.startsWith('voice/')) return 0.90;
  if (/^(bumper|sling|post)-/.test(name)) return 0.65;
  if (/^(skill-shot|combo-|mission-complete|jackpot|super-jackpot|rank-up|multiball|wizard)/.test(name)) return 0.95;
  if (/^(mission-|tilt|game-over)/.test(name)) return 0.80;
  return 0.70;
}
const sfx = (name) => { if (SFX) SFX.play(name, gainFor(name)); };
const sfxVariant = (name, n) => { if (SFX) SFX.playVariant(name, n, gainFor(`${name}-1`)); };

/** Event -> one-shot cue. Kept as data so the bank and the engine stay in step. */
const EVENT_SFX = {
  'target': 'drop-target',
  'target-bank-clear': 'drop-bank-clear',
  'rollover': 'gate',
  'saucer': 'saucer-in',
  'saucer-kick': 'saucer-kick',
  'ramp-enter': 'gate',
  'ramp-reject': 'post-1',
  'kickback': 'kickback',
  'drain': 'ball-drain',
  'plunge': 'plunger-release',
  'tilt-warn': 'tilt-warn',
  'tilt': 'tilt',
  'spinner': 'spinner-tick',
};

const el = (id) => document.getElementById(id);

const state = {
  world: null,
  rules: null,
  renderer: null,
  mode: 'classic',
  ballsLeft: 3,
  pendingKicks: [],
  running: false,
  paused: false,
  rolling: false,        // the end-of-ball bonus owns the score display
  last: 0,
  flashes: new Map(),
  input: { left: false, right: false, plunge: false },
  lit: [],
  resume: null,
  seed: 0,
  tape: null,
  roll: null,
  rampRoll: null,
  musicCalm: null,
  musicIntense: null,
  musicBed: 'calm',
  musicVolumes: { calm: 0, intense: 0 },
  musicFade: 0,
  raf: 0,
};

// ---------------------------------------------------------------------------
// Loop
// ---------------------------------------------------------------------------

function frame(now) {
  state.raf = requestAnimationFrame(frame);
  if (!state.world) return;

  const dt = state.last ? Math.min((now - state.last) / 1000, 0.25) : 0;
  state.last = now;

  if (state.running && !state.paused) {
    if (state.tape && state.tape.length < TAPE_FRAME_CAP) {
      // Round dt so the tape is stable JSON rather than full float noise; the
      // engine is fed the rounded value too, so replay matches exactly.
      const d = Math.round(dt * 100000) / 100000;
      const buttons = (state.input.left ? 1 : 0) | (state.input.right ? 2 : 0) | (state.input.plunge ? 4 : 0);
      state.tape.push([d, buttons]);
      advance(state.world, state.input, d);
    } else {
      advance(state.world, state.input, dt);
    }
    handleEvents(drainEvents(state.world));
    tickRules(state.rules, dt);
    runCommands(drainCommands(state.rules));
    runPendingKicks(dt);
    setBallsInPlay(state.rules, state.world.ballsInPlay);
    showLog(drainLog(state.rules));
    state.lit = litShots(state.rules);
    updateRollSound();
    if (state.resume) state.resume.changed();
    paint();
  }

  // Decay bumper flashes on real time, not on simulation steps, so they look
  // the same whether the tab is running fast or catching up.
  for (const [k, v] of state.flashes) {
    const next = v - dt;
    if (next <= 0) state.flashes.delete(k); else state.flashes.set(k, next);
  }

  state.renderer.draw(state.world, state.flashes, state.lit, dt);
}

function handleEvents(events) {
  for (const e of events) {
    // Feedback for the hit, before the ruleset decides what it is worth.
    if (e.type === 'bumper') {
      state.flashes.set(e.id, 0.12);
      const b = BUMPERS.find((x) => x.id === e.id);
      if (b) state.renderer.burst(b.x, b.y, 8, '255,226,170', 260);
      state.renderer.kick(2.6);
    } else if (e.type === 'sling') {
      state.flashes.set(e.id, 0.10);
      const w = SLING_POS[e.id];
      if (w) state.renderer.burst(w.x, w.y, 6, '255,190,150', 230);
      state.renderer.kick(2.0);
    }
    if (e.type === 'target') state.renderer.kick(1.2);

    // Round-robin variants so a bumper chain sounds busy rather than like a
    // machine gun. audio.js throttles retriggers; variants are the other half.
    if (e.type === 'bumper') sfxVariant('bumper', 3);
    else if (e.type === 'sling') sfxVariant('sling', 2);
    else if (e.type === 'post') sfxVariant('post', 2);
    else if (EVENT_SFX[e.type]) sfx(EVENT_SFX[e.type]);

    // The ruleset owns all scoring. This file only routes.
    applyEvent(state.rules, e);

    if (e.type === 'ball-lost') onBallLost();
    if (e.type === 'escaped') {
      // Should never happen. If it does it is a physics bug, and it must be
      // loud rather than quietly recovered from.
      console.warn('pinball: ball escaped the cabinet', e);
    }
  }
}

/**
 * rules.js is pure and cannot touch the world, so it emits commands instead.
 * This is the only place they are executed.
 */
function runCommands(commands) {
  for (const c of commands) {
    switch (c.type) {
      case 'release-saucer':
        if (c.delay) state.pendingKicks.push({ id: c.id, t: c.delay });
        else releaseSaucer(state.world, c.id);
        break;
      case 'celebrate':
        state.renderer.kick(5);
        break;
      case 'add-balls': {
        const from = SAUCERS.find((x) => x.id === 'lock') || { x: 408, y: 330 };
        for (let i = 0; i < c.count; i += 1) {
          addBall(state.world, from.x, from.y + i * 4, -260 - i * 40, 700);
        }
        break;
      }
      // Audio arrives at P5. Routing the cues now keeps the wiring honest: if
      // one is missing then, it will be missing HERE rather than never having
      // been emitted in the first place.
      case 'sound':
      case 'voice':
        sfx(c.name);
        break;
      case 'music':
        setMusic(c.bed);
        break;
      default:
        break;
    }
  }
}

// -- Continuous sound ------------------------------------------------------
// Ball roll and the music bed are loops, which the one-shot pool cannot do:
// it hands out a FINISHED voice, and a loop never finishes.

function setMusic(bed) {
  if (!SFX) return;
  const want = bed === 'intense' ? 'intense' : 'calm';
  if (!state.musicCalm) {
    // Start both beds together and leave them running. They share an exact
    // bar grid, so changing intensity is a gain crossfade, never a song reset.
    state.musicCalm = SFX.loop('music/bed-calm');
    state.musicIntense = SFX.loop('music/bed-intense');
    state.musicVolumes = { calm: 0, intense: 0 };
  }
  if (state.musicBed === want && state.musicVolumes[want] === 0.25) return;
  state.musicBed = want;
  if (state.musicFade) cancelAnimationFrame(state.musicFade);
  const from = { ...state.musicVolumes };
  const to = { calm: want === 'calm' ? 0.25 : 0, intense: want === 'intense' ? 0.25 : 0 };
  const started = performance.now();
  const fade = (now) => {
    const p = Math.min(1, (now - started) / 500);
    state.musicVolumes.calm = from.calm + (to.calm - from.calm) * p;
    state.musicVolumes.intense = from.intense + (to.intense - from.intense) * p;
    state.musicCalm.setVolume(state.musicVolumes.calm);
    state.musicIntense.setVolume(state.musicVolumes.intense);
    if (p < 1) state.musicFade = requestAnimationFrame(fade);
    else state.musicFade = 0;
  };
  state.musicFade = requestAnimationFrame(fade);
}

/** Roll volume and pitch follow the fastest ball, so the table sounds alive. */
function updateRollSound() {
  if (!SFX) return;
  const balls = state.world.balls.filter((b) => b.alive && !b.captured);
  const fastest = balls.reduce((m, b) => Math.max(m, Math.hypot(b.vx, b.vy)), 0);
  const onRamp = balls.some((b) => b.inRamp);

  if (!state.roll) {
    state.roll = SFX.loop('ball-roll');
    state.rampRoll = SFX.loop('ramp-roll');
    state.rampRoll.setVolume(0);
  }
  const n = Math.min(fastest / 2200, 1);
  state.roll.setVolume(onRamp ? 0 : 0.30 * n).setRate(0.7 + n * 0.8);
  state.rampRoll.setVolume(onRamp ? 0.30 : 0);
}

function stopContinuous() {
  if (state.roll) { state.roll.stop(); state.roll = null; }
  if (state.rampRoll) { state.rampRoll.stop(); state.rampRoll = null; }
  if (state.musicFade) { cancelAnimationFrame(state.musicFade); state.musicFade = 0; }
  if (state.musicCalm) { state.musicCalm.stop(); state.musicCalm = null; }
  if (state.musicIntense) { state.musicIntense.stop(); state.musicIntense = null; }
  state.musicBed = 'calm';
  state.musicVolumes = { calm: 0, intense: 0 };
}

function runPendingKicks(dt) {
  if (!state.pendingKicks.length) return;
  for (const k of state.pendingKicks) k.t -= dt;
  const due = state.pendingKicks.filter((k) => k.t <= 0);
  state.pendingKicks = state.pendingKicks.filter((k) => k.t > 0);
  for (const k of due) releaseSaucer(state.world, k.id);
}

function showLog(entries) {
  for (const entry of entries) announce(entry.text);
}

function onBallLost() {
  if (state.world.mode.endless) {
    serveBall(state.world);
    return;
  }

  // Ball save first: a saved ball is not a lost ball, so nothing advances --
  // not the ball number, not the bonus, not the count remaining.
  if (consumeBallSave(state.rules)) {
    serveBall(state.world);
    state.pendingKicks = [];
    announce('BALL SAVED');
    paint();
    return;
  }

  const bonus = nextBall(state.rules);

  // An extra ball is the same ball number over again, so it is spent here
  // rather than added to the count: the player sees "Ball 2 / 3" twice.
  if (consumeExtraBall(state.rules)) {
    state.rules.ball -= 1;
    armBallSave(state.rules);
    serveBall(state.world);
    state.pendingKicks = [];
    rollBonus(bonus, 'EXTRA BALL');
    return;
  }

  state.ballsLeft -= 1;
  if (state.ballsLeft <= 0) {
    // The final bonus is the one worth watching. Count it up, then end.
    state.running = false;
    rollBonus(bonus, 'Game over', () => gameOver(bonus));
    return;
  }
  serveBall(state.world);
  state.pendingKicks = [];
  rollBonus(bonus, `Ball ${state.rules.ball}`);
}

/*
 * The end-of-ball bonus was already tallied and paid; it was just handed over
 * instantly. The countdown IS the reward in pinball, so the SCORE DISPLAY is
 * animated up to the already-awarded total. Presentation only -- the rules
 * have the real number the whole time, so nothing here can desync the game.
 */
let rollTimer = 0;
function rollBonus(bonus, thenText, done) {
  clearInterval(rollTimer);
  const r = state.rules;
  if (!bonus || bonus <= 0) { state.rolling = false; announce(thenText); paint(); if (done) done(); return; }
  const steps = 12;
  const from = r.score - bonus;
  let i = 0;
  state.rolling = true;
  announce(`Bonus ${bonus.toLocaleString()}`);
  rollTimer = setInterval(() => {
    i += 1;
    const shown = Math.round(from + (bonus * i) / steps);
    el('pb-score').textContent = shown.toLocaleString();
    sfx('spinner-tick');
    if (i >= steps) {
      clearInterval(rollTimer);
      state.rolling = false;
      paint();
      announce(thenText);
      if (done) done();
    }
  }, 70);
}

function gameOver(bonus) {
  state.running = false;
  stopContinuous();
  clearInterval(rollTimer);
  state.rolling = false;
  sfx('game-over');
  const r = state.rules;
  if (bonus > 0) el('pb-score').textContent = r.score.toLocaleString();
  announce(`Game over. ${r.score.toLocaleString()} points.`);
  el('pb-overlay').hidden = false;
  el('pb-overlay-title').textContent = 'Game over';
  el('pb-overlay-body').textContent = `${r.score.toLocaleString()} points`;
  el('pb-overlay-note').textContent =
    `${RANKS[r.rank]} • ${r.missionsDone.length} of ${MISSIONS.length} missions`;
  showMatch(r.score);
  saveBest();
  if (state.resume) state.resume.clear();
  if (DAILY) markDailyDone();
  offerShare();
}

/**
 * Share on game over. The spoiler rule matters even here: the mission ORDER is
 * the daily's content, so the card reports how far you got, never which
 * missions came up.
 */
function offerShare() {
  if (!window.SnackPackShare) return;
  const r = state.rules;
  const filled = Math.min(r.missionsDone.length, MISSIONS.length);
  const row = '\u{1F7E9}'.repeat(filled) + '\u2B1C'.repeat(MISSIONS.length - filled);
  window.SnackPackShare.result({
    mount: document.querySelector('.pb-stage'),
    game: 'Pinball',
    puzzle: DAILY || undefined,
    headline: `${MODES[state.mode].label}: ${r.score.toLocaleString()} as ${RANKS[r.rank]}`,
    stats: [`${r.missionsDone.length}/${MISSIONS.length} missions`, `ball ${r.ball}`],
    grid: [row],
  });
}

const dailyKey = () => `pinball_daily_${DAILY}`;

function dailyAlreadyPlayed() {
  if (!DAILY) return false;
  try {
    if (window.SnackPackStore) return !!window.SnackPackStore.get('pinball', 'daily', DAILY);
    return !!localStorage.getItem(`sp_${dailyKey()}`);
  } catch (err) { return false; }
}

function markDailyDone() {
  try {
    const v = String(state.rules.score);
    if (window.SnackPackStore) window.SnackPackStore.set('pinball', 'daily', DAILY, v);
    else localStorage.setItem(`sp_${dailyKey()}`, v);
  } catch (err) { /* storage can be blocked; never break the game over it */ }
}

// ---------------------------------------------------------------------------
// Persistence -- arcade convention, sp_-prefixed via SnackPackStore
// ---------------------------------------------------------------------------

const bestKey = () => `pinball_best_${state.mode}`;

function readBest() {
  try {
    if (window.SnackPackStore) return Number(window.SnackPackStore.get('pinball', 'best', state.mode)) || 0;
    return Number(localStorage.getItem(`sp_${bestKey()}`)) || 0;
  } catch (err) { return 0; }
}

function saveBest() {
  try {
    if (state.rules.score <= readBest()) return;
    if (window.SnackPackStore) window.SnackPackStore.set('pinball', 'best', state.mode, state.rules.score);
    else localStorage.setItem(`sp_${bestKey()}`, String(state.rules.score));
  } catch (err) { /* storage can be blocked; never break the game over it */ }
}

