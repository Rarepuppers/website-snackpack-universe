/**
 * make-silent-audio.mjs -- write a silent placeholder for every cue in the
 * pinball bank.
 *
 * The cues are wired and firing now; the real recordings arrive from Codex per
 * docs/pinball/05-codex-art-brief.md. Without placeholders every cue is a 404,
 * and audio.js's promise-rejection guard does not stop the browser logging a
 * failed network request -- so the live console fills with errors for a game
 * that is working correctly.
 *
 * This is the same convention the arcade already uses for art: placeholders
 * ship so nothing 404s, and are listed so nobody mistakes them for finished.
 *
 * Only writes files that do not already exist, so it can never overwrite a
 * real recording. Re-run it after adding a cue.
 *
 * Usage: node tools/pinball/make-silent-audio.mjs
 */

import fs from 'node:fs';
import path from 'node:path';

// The arcade's shared audio lives under play/, not at the repo root: audio.js
// resolves names relative to its own directory. Writing to a root-level
// shared-assets/ produced a full bank of files that nothing could load.
const ROOT = path.resolve('play/shared-assets/game-ui/audio/pinball');

const ONE_SHOTS = [
  // Mechanical
  'flipper-up', 'flipper-down', 'plunger-pull', 'plunger-release',
  'drop-target', 'drop-bank-clear', 'gate', 'saucer-in', 'saucer-kick',
  'lock', 'kickback', 'ball-drain',
  // Rubber, round-robin variants
  'bumper-1', 'bumper-2', 'bumper-3', 'sling-1', 'sling-2', 'post-1', 'post-2',
  // Rules and celebration
  'skill-shot', 'combo-2', 'combo-3', 'combo-4',
  'mission-start', 'mission-complete', 'mission-fail',
  'jackpot', 'super-jackpot', 'rank-up', 'multiball-start',
  'wizard-start', 'wizard-complete', 'tilt-warn', 'tilt', 'game-over',
];

const LOOPS = ['ball-roll', 'ramp-roll', 'spinner-tick'];

const VOICE = [
  ...Array.from({ length: 12 }, (_, i) => `mission-${i + 1}`),
  'voice-rank-up', 'voice-multiball', 'voice-jackpot',
  'voice-wizard', 'voice-complete', 'voice-tilt',
];

const MUSIC = ['bed-calm', 'bed-intense'];

/** A valid mono 44.1 kHz 16-bit PCM WAV of `seconds` of silence. */
function silentWav(seconds) {
  const rate = 44100;
  const samples = Math.max(1, Math.round(rate * seconds));
  const dataBytes = samples * 2;
  const buf = Buffer.alloc(44 + dataBytes);
  buf.write('RIFF', 0);
  buf.writeUInt32LE(36 + dataBytes, 4);
  buf.write('WAVE', 8);
  buf.write('fmt ', 12);
  buf.writeUInt32LE(16, 16);      // fmt chunk size
  buf.writeUInt16LE(1, 20);       // PCM
  buf.writeUInt16LE(1, 22);       // mono
  buf.writeUInt32LE(rate, 24);
  buf.writeUInt32LE(rate * 2, 28); // byte rate
  buf.writeUInt16LE(2, 32);        // block align
  buf.writeUInt16LE(16, 34);       // bits per sample
  buf.write('data', 36);
  buf.writeUInt32LE(dataBytes, 40);
  return buf; // the sample data is already zeroed
}

let written = 0;
let kept = 0;

function emit(dir, name, seconds) {
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `${name}.wav`);
  if (fs.existsSync(file)) { kept += 1; return; }
  fs.writeFileSync(file, silentWav(seconds));
  written += 1;
}

for (const n of ONE_SHOTS) emit(ROOT, n, 0.12);
for (const n of LOOPS) emit(ROOT, n, 0.5);
for (const n of VOICE) emit(path.join(ROOT, 'voice'), n, 0.6);
for (const n of MUSIC) emit(path.join(ROOT, 'music'), n, 1.0);

const note = path.join(ROOT, 'PLACEHOLDERS.txt');
if (!fs.existsSync(note)) {
  fs.writeFileSync(note,
    'Every .wav in this folder is SILENT PLACEHOLDER audio, generated by\n'
    + 'tools/pinball/make-silent-audio.mjs so the wired cues do not 404.\n\n'
    + 'They are not finished assets. Codex replaces them per\n'
    + 'docs/pinball/05-codex-art-brief.md, PRIORITY 4. Overwriting a file here\n'
    + 'with a real recording is the intended workflow; the generator never\n'
    + 'overwrites an existing file.\n');
}

console.log(`silent audio placeholders: ${written} written, ${kept} already present`);
console.log(`total cues in the bank: ${ONE_SHOTS.length + LOOPS.length + VOICE.length + MUSIC.length}`);
